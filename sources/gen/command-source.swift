import FolioActions
import FolioDomain
import Foundation

enum CommandSource {
    static func header(query: Bool = false) -> [String] {
        [
            query
                ? "// Generated by `mise run gen-cli` from the @Query declarations in sources/actions. Do not edit."
                : "// Generated by `mise run gen-cli` from the actions' @Action declarations. Do not edit.",
            "import ArgumentParser",
            "import FolioActions",
            "import FolioDomain",
            "import Foundation",
            "",
        ]
    }

    static let commandsEnum = (header() + ["enum GeneratedCommands {}"]).joined(separator: "\n") + "\n"

    // 액션 파일마다 같은 자리(sources/cli/generated/<액션 폴더>/<같은 이름>)에 명령 하나를 쓴다.
    static func file(_ type: any Action.Type) -> String { file(String(describing: type), Shape(type.spec)) }

    static func file(_ type: any Query.Type) -> String { file(String(describing: type), Shape(type.spec)) }

    static func file(_ name: String, _ shape: Shape) -> String {
        let lines = header(query: shape.query) + ["extension GeneratedCommands {"] + command(name, shape).map { "    " + $0 } + ["}"]
        return lines.map { $0.allSatisfy(\.isWhitespace) ? "" : $0 }.joined(separator: "\n") + "\n"
    }

    // 액션과 읽기 선언이 명령에 넘기는 것이다. 읽기는 확인을 받지 않고, 결과를 `show`로 그린다.
    struct Shape {
        var command: String
        var summary: String
        var discussion: String
        var examples: [String]
        var asks: Bool
        var query: Bool
        var fields: [FieldSpec]

        init(_ spec: ActionSpec) {
            (command, summary, discussion, examples) = (spec.command, spec.summary, spec.discussion, spec.examples)
            (asks, query, fields) = (spec.effect == .removes || spec.effect == .moves, false, spec.fields)
        }

        init(_ spec: QuerySpec) {
            (command, summary, discussion, examples) = (spec.command, spec.summary, spec.discussion, spec.examples)
            (asks, query, fields) = (false, true, spec.fields)
        }
    }

    static func command(_ name: String, _ spec: Shape) -> [String] {
        let words = spec.command.split(separator: " ")
        let fields = spec.fields
        let course = fields.first { $0.ref == .course && $0.role == .argument && !$0.many }
        let folded = course.flatMap { c in
            c.optional ? nil : fields.first { $0.role == .argument && $0.ref?.foldsIntoCourse == true && $0.name != c.name }
        }

        var discussion = spec.discussion.isEmpty ? [] : spec.discussion.components(separatedBy: "\n") + [""]
        if spec.asks { discussion += ["실행하기 전에 확인을 받는다.", ""] }
        if !spec.examples.isEmpty { discussion += ["예시:"] + spec.examples.map { "  " + $0 } }
        var out = [
            "struct \(name): ParsableCommand {",
            "    static let configuration = CommandConfiguration(commandName: \(q(String(words.last!)))\(spec.summary.isEmpty ? "" : ", abstract: \(q(spec.summary))"), discussion: \"\"\"",
        ]
        out += discussion.map { $0.isEmpty ? "" : "        " + escaped($0) } + ["        \"\"\")", "    @OptionGroup var g: GlobalOptions"]

        for f in fields where f.name != course?.name || folded == nil {
            // ArgumentParser는 기본값이 있는 위치 인자 뒤에 다른 위치 인자가 오면 거부한다.
            let last = !fields.contains { $0.role == .argument && fields.firstIndex(of: $0)! > fields.firstIndex(of: f)! }
            if let folded, f.name == folded.name {
                let item = f.help.isEmpty ? f.name : f.help
                let completion = f.ref.map { "completion: Complete.ref(.\(caseName($0)))" } ?? ""
                if f.many {
                    let one = f.name.hasSuffix("s") ? String(f.name.dropLast()) : f.name
                    out.append(
                        "    @Argument(help: ArgumentHelp(\(q("<과목>/<\(item)>. 둘째부터는 \(item)만 써도 된다")), valueName: \(q(one))), \(completion)) var \(f.name): [String]"
                    )
                } else {
                    out.append(
                        "    @Argument(help: ArgumentHelp(\(q("<과목>/<\(item)>")), valueName: \(q(f.name))), \(completion)) var \(f.name): String"
                            + (last ? " = \"\"" : ""))
                }
                continue
            }
            if let line = declaration(f, last: last) { out.append("    " + line) }
        }

        out.append("")
        out.append("    func run() throws {")

        let patches = spec.query ? [] : fields.filter { $0.patch && $0.role != .hidden }
        if !patches.isEmpty, patches.count == fields.filter({ !($0.role == .argument && $0.ref != nil) && $0.role != .hidden }).count {
            let given = patches.map { $0.many ? "!\($0.name).isEmpty" : "\($0.name) != nil" }.joined(separator: " || ")
            let flags = patches.map { "--" + flag($0) }.joined(separator: ", ")
            out.append("        guard \(given) else { throw CLIError(exit: .usage, message: \(q("바꿀 것을 하나 이상 주세요: \(flags)"))) }")
        }

        out.append("        let ctx = try CLI.context(g)")
        if course != nil || fields.contains(where: { $0.ref != nil && $0.role != .new && $0.role != .hidden || $0.parsed != nil }) {
            out.append("        let r = Resolver(ctx)")
        }
        if let course {
            if let folded {
                out.append(
                    folded.many
                        ? "        let (c, \(folded.name)First) = try r.split(\(folded.name).first ?? \"\")"
                        : "        let (c, \(folded.name)Name) = try r.split(\(folded.name))")
            } else if course.optional {
                out.append("        let c = try \(course.name).map { try r.course($0) }")
            } else {
                out.append("        let c = try r.course(\(course.name))")
            }
        }

        let scope = course == nil ? "nil" : "c"
        var exprs: [String: String] = [:]
        for f in fields where parent(f, in: fields) == nil {
            if f.name == course?.name {
                exprs[f.name] = f.optional ? "c?.id" : "c.id"
            } else if f.name == folded?.name, f.many {
                exprs[f.name] = "try ([\(f.name)First] + \(f.name).dropFirst()).map { \(resolve(f, "$0")) }"
            } else if f.name == folded?.name {
                exprs[f.name] = resolve(f, "\(f.name)Name")
            } else {
                exprs[f.name] = value(f, scope: scope)
            }
        }
        for f in fields { if let p = parent(f, in: fields) { exprs[f.name] = value(f, scope: scope, parent: exprs[p.name]) } }

        let values = fields.map { "            \($0.name): \(exprs[$0.name]!)" }
        let value = spec.query ? "query" : "action"
        out.append("        let \(value) = FolioActions.\(name)(")
        out += values.enumerated().map { $0.offset == values.count - 1 ? $0.element : $0.element + "," }
        out.append("        )")
        out.append(spec.query ? "        try show(query, g, ctx: ctx)" : "        try perform(spec: action, g, ctx: ctx)")
        out.append("    }")
        out.append("}")
        return out
    }

    static func parent(_ f: FieldSpec, in fields: [FieldSpec]) -> FieldSpec? {
        guard let p = f.ref?.parent else { return nil }
        return fields.first { $0.ref == p && !$0.many && !$0.optional }
    }

    // 생성한 명령이 `ItemKind`의 경우를 이름으로 부른다. 경우 이름은 원래 값(타입 이름)의 첫 글자를 소문자로 바꾼 것이다.
    static func caseName(_ kind: ItemKind) -> String { kind.rawValue.prefix(1).lowercased() + kind.rawValue.dropFirst() }

    static func resolve(_ f: FieldSpec, _ value: String) -> String {
        f.ref.map { "try r.\(lookup($0))(.\(caseName($0)), \(value), in: c)" } ?? value
    }

    static func lookup(_ kind: ItemKind) -> String { kind.byPath ? "path" : "id" }

    static func flag(_ f: FieldSpec) -> String { f.cliName ?? kebab(f.name) }

    static func cliType(_ f: FieldSpec) -> String {
        if f.ref != nil || f.file != nil || f.folder || f.parsed != nil { return "String" }
        if f.type == "Bool", f.patch { return "Toggle" }
        return f.type == "Date" ? "DateArg" : f.type
    }

    static func help(_ f: FieldSpec, valueName given: String? = nil) -> String {
        var text = [f.help, f.parsedForm ?? ""].filter { !$0.isEmpty }.joined(separator: ". ")
        if f.patch, f.optional { text += text.isEmpty ? "none이면 지운다" : ". none이면 지운다" }
        if f.many, f.file == nil || f.filePerItem {
            let given = f.parsed != nil ? "none이면 비운다" : "주면 목록 전체를 바꾸고, none이면 비운다"
            text += (text.isEmpty ? "" : ". ") + (f.patch ? "여러 번 줄 수 있다. " + given : "여러 번 줄 수 있다")
        }
        let valueName = given ?? f.parsed ?? (f.ref != nil ? flag(f) : f.type == "LocalDate" || f.type == "Date" ? "date" : nil)
        return valueName.map { "ArgumentHelp(\(q(text)), valueName: \(q($0)))" } ?? q(text)
    }

    static func declaration(_ f: FieldSpec, last: Bool) -> String? {
        let t = cliType(f)
        let completion = f.ref.map { ", completion: Complete.ref(.\(caseName($0)))" } ?? ""
        let name = f.cliName.map { "name: .customLong(\(q($0))), " } ?? ""
        if f.file != nil || f.folder {
            let json = f.file != nil && !(f.type == "String" && !f.many)
            let complete = f.folder ? ".directory" : json ? ".file(extensions: [\"json\"])" : ".file()"
            let help = help(f, valueName: f.file ?? "folder")
            let type = f.filePerItem ? "[String]" : f.optional ? "String?" : "String"
            let wrapper = f.role == .argument ? "@Argument(" : "@Option(\(name)"
            return "\(wrapper)help: \(help), completion: \(complete)) var \(f.name): \(type)"
        }
        switch f.role {
        case .hidden: return nil
        case .new: return "@Option(name: .customLong(\"id\"), help: .hidden) var \(f.name): UUID?"
        case .off(let flag): return "@Flag(name: .customLong(\(q(flag))), help: \(q(f.help))) var \(camel(flag)) = false"
        case .argument:
            if f.ref != nil, !f.optional, !f.many {
                return "@Argument(help: \(help(f))\(completion)) var \(f.name): String" + (last ? " = \"\"" : "")
            }
            if f.many {
                return "@Argument(help: \(help(f))\(completion)) var \(f.name): [\(t)]" + (f.defaultValue.map { " = \($0)" } ?? "")
            }
            if f.optional { return "@Argument(help: \(help(f))\(completion)) var \(f.name): \(t)?" }
            return "@Argument(help: \(help(f))\(completion)) var \(f.name): \(t)" + (f.defaultValue.map { " = \($0)" } ?? "")
        case .option:
            if f.type == "Bool", !f.patch, !f.many { return "@Flag(\(name)help: \(help(f))) var \(f.name) = \(f.defaultValue ?? "false")" }
            if f.patch, f.many { return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): [\(t)] = []" }
            if f.patch { return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): \(f.optional ? "Clearable<\(t)>" : t)?" }
            if f.many { return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): [\(t)] = []" }
            if f.optional { return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): \(t)?" }
            if let d = f.defaultValue, f.type != "Date" {
                return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): \(t) = \(d)"
            }
            return "@Option(\(name)help: \(help(f))\(completion)) var \(f.name): \(t)"
        }
    }

    static func value(_ f: FieldSpec, scope: String, parent: String? = nil) -> String {
        switch f.role {
        case .hidden: return f.defaultValue ?? (f.patch ? ".keep" : "nil")
        case .new: return "\(f.name) ?? UUID()"
        case .off(let flag): return "!\(camel(flag))"
        default: break
        }
        if f.folder { return f.optional ? "\(f.name).map(absolute)" : "absolute(\(f.name))" }
        if f.file != nil {
            if f.type == "String", !f.many { return f.optional ? "try \(f.name).map(readText)" : "try readText(\(f.name))" }
            if f.filePerItem { return "try \(f.name).map { try readJSONFile(\(f.type).self, $0) }" }
            let type = f.many ? "[\(f.type)]" : f.type
            return f.optional ? "try \(f.name).map { try readJSONFile(\(type).self, $0) }" : "try readJSONFile(\(type).self, \(f.name))"
        }
        let t = f.ref == nil && f.parsed == nil ? "" : "try "
        func one(_ v: String) -> String {
            if f.parsed != nil { return "try r.parse(\(v), in: \(scope))" }
            if let ref = f.ref {
                return "try r.\(lookup(ref))(.\(caseName(ref)), \(v), in: \(scope)\(parent.map { ", parent: \($0)" } ?? ""))"
            }
            return f.type == "Date" || f.type == "Bool" && f.patch ? "\(v).\(f.type == "Date" ? "date" : "value")" : v
        }
        let identity = f.ref == nil && f.parsed == nil && f.type != "Date" && !(f.type == "Bool" && f.patch)
        if f.patch, f.many {
            return "\(f.name).isEmpty ? .keep : .set(\(t)\(f.name).clearing.map { \(one("$0")) })"
        }
        if f.patch {
            if f.optional {
                return "\(t)\(f.name).map { p in Patch.set(\(identity ? "p.value" : "\(t)p.value.map { \(one("$0")) }")) } ?? .keep"
            }
            return "\(t)\(f.name).map { Patch.set(\(one("$0"))) } ?? .keep"
        }
        if f.many || f.optional { return identity ? f.name : "\(t)\(f.name).map { \(one("$0")) }" }
        return one(f.name)
    }

    static func q(_ s: String) -> String { "\"" + escaped(s) + "\"" }
    static func escaped(_ s: String) -> String {
        s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    }
    static func camel(_ s: String) -> String {
        let parts = s.split(separator: "-")
        return String(parts[0]) + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
    }
    // ArgumentParser가 옵션 이름을 짓는 방식을 따른다. `minGPA`는 `min-gpa`, `latesPerAbsence`는 `lates-per-absence`가
    // 된다.
    static func kebab(_ s: String) -> String {
        let chars = Array(s)
        return chars.indices.reduce(into: "") { out, i in
            let ch = chars[i]
            let starts = ch.isUppercase && i > 0 && (!chars[i - 1].isUppercase || i + 1 < chars.count && chars[i + 1].isLowercase)
            out += (starts ? "-" : "") + ch.lowercased()
        }
    }
}
