import FolioActions
import Foundation
import SwiftParser
import SwiftSyntax

// 명령 트리는 sources/cli/commands에서 읽는다. 손 명령 타입 안이나 그 `extension`에 선언한 하위 명령과, 명령 낱말이 그
// 타입의 경로와 같은 생성 명령이 그 타입의 하위 명령이다. 손 명령의 configuration은 `subcommands: subcommandTypes`로 이
// 목록을 받는다.
enum CommandTree {
    static func scan(_ root: URL) throws -> [HandCommand] {
        var found: [HandCommand] = []
        func visit(_ members: MemberBlockItemListSyntax, owner: HandCommand) {
            for member in members {
                guard let (name, block) = commandDecl(member.decl) else { continue }
                let command = HandCommand(
                    path: owner.path + [name], words: owner.words + [commandName(block) ?? argumentParserName(name)])
                found.append(command)
                visit(block.members, owner: command)
            }
        }
        for path in swiftFiles(under: root) {
            let tree = Parser.parse(source: try String(contentsOf: root.appending(path: path), encoding: .utf8))
            for item in tree.statements {
                guard case .decl(let decl) = item.item else { continue }
                if let (name, block) = commandDecl(decl) {
                    let root = HandCommand(path: [name], words: [commandName(block) ?? argumentParserName(rootName(name))])
                    found.append(root)
                    visit(block.members, owner: root)
                } else if let ext = decl.as(ExtensionDeclSyntax.self) {
                    let path = ext.extendedType.trimmedDescription.split(separator: ".").map(String.init)
                    // 확장하는 타입은 다른 파일에 있으므로, 낱말은 나중에 그 타입을 찾아 채운다.
                    visit(ext.memberBlock.members, owner: HandCommand(path: path, words: []))
                }
            }
        }
        // extension에서 찾은 명령의 낱말을 그 바깥 타입의 낱말로 고친다.
        let byPath = Dictionary(found.filter { $0.path.count == 1 }.map { ($0.path, $0) }, uniquingKeysWith: { a, _ in a })
        func words(of path: [String]) -> [String] {
            guard let command = found.first(where: { $0.path == path }) else { return [] }
            if path.count == 1 { return byPath[path]?.words ?? command.words }
            return words(of: Array(path.dropLast())) + command.words.suffix(1)
        }
        return found.map { HandCommand(path: $0.path, words: words(of: $0.path)) }
    }

    static func source(_ hand: [HandCommand], generated: [any Action.Type]) throws -> String {
        let generated = generated.filter { $0.spec.generated }
        var lines = [
            "// Generated by `mise run gen-cli` from the commands in sources/cli/commands and the actions. Do not edit.",
            "import ArgumentParser",
            "",
        ]
        let owners = Dictionary(hand.map { ($0.words.joined(separator: " "), $0) }, uniquingKeysWith: { a, _ in a })
        var children: [[String]: [String]] = [:]
        for command in hand where command.path.count > 1 {
            children[Array(command.path.dropLast()), default: []].append(command.path.joined(separator: ".") + ".self")
        }
        for type in generated {
            let group = type.spec.command.split(separator: " ").dropLast().joined(separator: " ")
            guard let owner = owners[group] else {
                throw GenError("no command type in sources/cli/commands is `folio \(group)` for \(type.spec.command)")
            }
            children[owner.path, default: []].append("GeneratedCommands.\(String(describing: type)).self")
        }
        for (owner, types) in children.sorted(by: { $0.key.joined(separator: ".") < $1.key.joined(separator: ".") }) {
            lines += [
                "extension \(owner.joined(separator: ".")) {",
                "    static let subcommandTypes: [any ParsableCommand.Type] = alphabetical([",
            ]
            lines += types.sorted().map { "        \($0)," }
            lines += ["    ])", "}", ""]
        }
        return lines.dropLast().joined(separator: "\n") + "\n"
    }

    // ParsableCommand를 따르는 struct와 enum만 명령이다.
    static func commandDecl(_ decl: DeclSyntax) -> (String, MemberBlockSyntax)? {
        if let s = decl.as(StructDeclSyntax.self), conforms(s.inheritanceClause) { return (s.name.text, s.memberBlock) }
        if let e = decl.as(EnumDeclSyntax.self), conforms(e.inheritanceClause) { return (e.name.text, e.memberBlock) }
        return nil
    }

    static func conforms(_ clause: InheritanceClauseSyntax?) -> Bool {
        clause?.inheritedTypes.contains { ["ParsableCommand", "AsyncParsableCommand"].contains($0.type.trimmedDescription) } ?? false
    }

    static func commandName(_ block: MemberBlockSyntax) -> String? {
        for member in block.members {
            guard let variable = member.decl.as(VariableDeclSyntax.self),
                variable.bindings.first?.pattern.trimmedDescription == "configuration",
                let call = variable.bindings.first?.initializer?.value.as(FunctionCallExprSyntax.self),
                let argument = call.arguments.first(where: { $0.label?.text == "commandName" }),
                let literal = argument.expression.as(StringLiteralExprSyntax.self)
            else { continue }
            return literal.segments.trimmedDescription
        }
        return nil
    }

    static func rootName(_ name: String) -> String { name.hasSuffix("Command") ? String(name.dropLast("Command".count)) : name }

    // ArgumentParser가 commandName을 주지 않은 명령의 이름을 짓는 방식이다(`PlanCheck`: plan-check).
    static func argumentParserName(_ name: String) -> String { CommandSource.kebab(name) }
}
