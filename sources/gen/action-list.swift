import Foundation
import SwiftParser
import SwiftSyntax

// Swift는 실행 중에 타입을 찾지 못한다. 그래서 액션 목록은 sources/actions의 @Action 선언을 읽어 만든다. 선언이 `#if` 안에
// 있으면(macOS에서만 되는 백업) 목록에서도 같은 조건 안에 둔다. `#elseif`와 `#else` 절은 앞 절의 조건이 모두 거짓이어야
// 하므로 앞 절의 부정을 함께 건다. 조건마다 괄호로 묶어야 `a || b`를 다른 조건과 이을 때 우선순위가 바뀌지 않는다.
enum ActionList {
    static func scan(_ root: URL) throws -> [DeclaredAction] {
        var found: [DeclaredAction] = []
        for path in swiftFiles(under: root) {
            let tree = Parser.parse(source: try String(contentsOf: root.appending(path: path), encoding: .utf8))
            func visit(_ items: CodeBlockItemListSyntax, condition: [String]) {
                for item in items {
                    guard case .decl(let decl) = item.item else { continue }
                    if let ifConfig = decl.as(IfConfigDeclSyntax.self) {
                        var earlier: [String] = []
                        for clause in ifConfig.clauses {
                            let own = clause.condition?.trimmedDescription
                            if case .statements(let inner) = clause.elements {
                                visit(inner, condition: condition + earlier.map { "!(\($0))" } + (own.map { [$0] } ?? []))
                            }
                            if let own { earlier.append(own) }
                        }
                        continue
                    }
                    guard let node = decl.as(StructDeclSyntax.self),
                        node.attributes.contains(where: { $0.as(AttributeSyntax.self)?.attributeName.trimmedDescription == "Action" })
                    else { continue }
                    found.append(
                        DeclaredAction(
                            name: node.name.text, path: path,
                            condition: condition.count < 2
                                ? condition.first : condition.map { "(\($0))" }.joined(separator: " && ")))
                }
            }
            visit(tree.statements, condition: [])
        }
        return found.sorted { $0.path < $1.path }
    }

    static func source(_ actions: [DeclaredAction]) -> String {
        let everywhere = actions.filter { $0.condition == nil }
        let conditional = Dictionary(grouping: actions.compactMap { action in action.condition.map { ($0, action) } }, by: \.0)
        var lines = [
            "// Generated by `mise run gen-cli` from the @Action declarations in sources/actions. Do not edit.",
            "extension Actions {",
            "    public static let all: [any Action.Type] = everywhere + platform",
            "",
            "    static let everywhere: [any Action.Type] = [",
        ]
        lines += everywhere.map { "        \($0.name).self," }
        lines += ["    ]", "", "    static var platform: [any Action.Type] {", "        var list: [any Action.Type] = []"]
        for (condition, group) in conditional.sorted(by: { $0.key < $1.key }) {
            lines.append("        #if " + condition)
            lines += group.map { "        list.append(\($0.1.name).self)" }
            lines.append("        #endif")
        }
        lines += ["        return list", "    }", "}"]
        return lines.joined(separator: "\n") + "\n"
    }
}

func swiftFiles(under root: URL) -> [String] {
    guard let walker = FileManager.default.enumerator(atPath: root.path) else { return [] }
    return walker.compactMap { $0 as? String }.filter { $0.hasSuffix(".swift") && !$0.hasPrefix("generated/") }.sorted()
}
